// One-time local setup: puts the two development secrets into .NET user secrets, which live in
// the user profile and never in the repository.
//
// Both values are generated here rather than shipped, so no credential is shared between clones
// and nothing secret is ever committed. The generated demo password is written to a gitignored
// file instead of the console, because a password echoed into a terminal ends up in shell history
// and scrollback.

import { execFileSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const apiProject = join(repoRoot, 'api', 'src', 'FileInviteLite.Api')
const credentialsFile = join(repoRoot, '.local', 'dev-credentials.txt')

const DEMO_EMAIL = 'demo@fileinvite-lite.local'

function dotnet(args) {
  return execFileSync('dotnet', args, { cwd: repoRoot, encoding: 'utf8' })
}

function existingSecrets() {
  try {
    return dotnet(['user-secrets', 'list', '--project', apiProject])
  } catch {
    return ''
  }
}

function setSecret(key, value) {
  dotnet(['user-secrets', 'set', key, value, '--project', apiProject])
}

const current = existingSecrets()

if (current.includes('Jwt:SigningKey')) {
  console.log('Jwt:SigningKey is already set — leaving it alone.')
} else {
  setSecret('Jwt:SigningKey', randomBytes(48).toString('base64url'))
  console.log('Generated Jwt:SigningKey into user secrets.')
}

if (current.includes('Seed:DemoStaffPassword')) {
  console.log('Seed:DemoStaffPassword is already set — leaving it alone.')
  console.log(`Demo sign-in: ${DEMO_EMAIL} (password unchanged; see ${credentialsFile})`)
} else {
  const password = randomBytes(18).toString('base64url')
  setSecret('Seed:DemoStaffPassword', password)

  mkdirSync(dirname(credentialsFile), { recursive: true })
  writeFileSync(
    credentialsFile,
    [
      'Local development credentials for FileInvite-Lite.',
      'Generated by scripts/dev-setup.mjs. This folder is gitignored — keep it that way.',
      '',
      `email:    ${DEMO_EMAIL}`,
      `password: ${password}`,
      '',
    ].join('\n'),
    { encoding: 'utf8' },
  )

  console.log(`Generated the demo staff password. It is in ${credentialsFile}`)
}

console.log('\nSetup complete. Run the app with: npm run dev')
